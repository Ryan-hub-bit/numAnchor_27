#!/usr/bin/env python3
"""
Combine function-inline export files for function-level pretraining.

Input format:
- multiple ``*_functions.txt`` files generated by ``func_gen.py``
- each line is one full function encoded as tab-separated instructions

Output format:
- shuffled train/val corpora, still one function per line
"""

import os
import random
import re
from collections import Counter
from pathlib import Path

from tqdm import tqdm


def collect_all_files(base_dir, recursive=False):
    """Collect all *_functions.txt files from a directory."""
    base_path = Path(base_dir)
    if not base_path.exists():
        print(f"[WARNING] Directory not found: {base_dir}")
        return []

    files = list(base_path.rglob("*_functions.txt")) if recursive else list(base_path.glob("*_functions.txt"))
    mode = "recursively" if recursive else "in top level"
    print(f"[INFO] Found {len(files)} files {mode} under {base_dir}")
    return files


def get_top_symbols(file_list, top_n=400, output_file=None):
    """
    Analyze all files and find the top N most common dot-prefixed symbols.
    Non-top symbols can later be collapsed into ``.plt``.
    """
    pattern = re.compile(r"\.([a-zA-Z_][a-zA-Z0-9_]*)")
    counts = Counter()

    print(f"[INFO] Analyzing symbol frequencies across {len(file_list)} files...")
    for filepath in tqdm(file_list, desc="Analyzing symbols"):
        with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                counts.update(pattern.findall(line))

    top_symbols = set(symbol for symbol, _ in counts.most_common(top_n))

    print(f"\n[INFO] Found {len(counts)} unique symbols")
    print(f"[INFO] Keeping top {top_n} symbols, replacing {max(0, len(counts) - top_n)} with .plt")

    if output_file:
        with open(output_file, "w", encoding="utf-8") as f:
            for symbol, count in counts.most_common(top_n):
                f.write(f".{symbol}\t{count}\n")
        print(f"[INFO] Saved top {top_n} symbols to: {output_file}")

    return top_symbols, pattern


def load_top_symbols(symbols_file):
    """Load a precomputed top-symbol list."""
    with open(symbols_file, "r", encoding="utf-8") as f:
        top_symbols = set(line.split("\t")[0].lstrip(".") for line in f if line.strip())
    pattern = re.compile(r"\.([a-zA-Z_][a-zA-Z0-9_]*)")
    print(f"[INFO] Loaded {len(top_symbols)} symbols from {symbols_file}")
    return top_symbols, pattern


def smart_merge_line(line, top_symbols, pattern):
    """Replace low-frequency symbols with .plt in one line."""

    def replace_symbol(match):
        symbol_name = match.group(1)
        if symbol_name in top_symbols:
            return match.group(0)
        return ".plt"

    return pattern.sub(replace_symbol, line)


def count_lines_in_file(filepath):
    """Count lines in a file."""
    with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
        return sum(1 for _ in f)


def sample_lines_from_file(filepath, sample_ratio, top_symbols=None, pattern=None):
    """Read lines from one file, optionally apply smart merge, and sample."""
    lines = []
    with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            if top_symbols is not None and pattern is not None:
                line = smart_merge_line(line, top_symbols, pattern)
            if sample_ratio >= 1.0 or random.random() < sample_ratio:
                lines.append(line)
    return lines


def write_lines(lines, output_path):
    """Write lines to output file."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        for line in lines:
            f.write(line + "\n")
    print(f"[INFO] Wrote {len(lines):,} lines to {output_path}")


def split_train_val(lines, val_ratio):
    """Split already shuffled lines into train/val."""
    if val_ratio <= 0.0:
        return lines, []
    val_size = int(len(lines) * val_ratio)
    if val_size <= 0:
        return lines, []
    return lines[val_size:], lines[:val_size]


def main():
    import argparse
    import sys

    parser = argparse.ArgumentParser(description="Combine *_functions.txt files for function-level pretraining")
    parser.add_argument("--input_dir", required=True, help="Directory containing *_functions.txt files")
    parser.add_argument("--output_dir", required=True, help="Output directory")
    parser.add_argument("--train_output_name", default="train_functions.txt", help="Train output file name")
    parser.add_argument("--val_output_name", default="val_functions.txt", help="Validation output file name")
    parser.add_argument("--val_ratio", type=float, default=0.05, help="Validation split ratio")
    parser.add_argument("--top_n", type=int, default=400, help="Number of top symbols to keep")
    parser.add_argument("--sample_ratio", type=float, default=1.0, help="Sampling ratio before splitting")
    parser.add_argument("--enable_smart_merge", action="store_true", help="Collapse low-frequency symbols into .plt")
    parser.add_argument("--recursive", action="store_true", help="Recursively search for *_functions.txt files")
    parser.add_argument("--seed", type=int, default=42, help="Shuffle seed")
    args = parser.parse_args()

    random.seed(args.seed)

    output_dir = args.output_dir
    train_output = os.path.join(output_dir, args.train_output_name)
    val_output = os.path.join(output_dir, args.val_output_name)
    symbols_file = os.path.join(output_dir, "top_symbols_functions.txt")

    print("=" * 70)
    print("FUNCTION-LEVEL PRETRAINING DATA COMBINATION")
    print("=" * 70)
    print(f"Input directory: {args.input_dir}")
    print(f"Train output: {train_output}")
    print(f"Val output: {val_output}")
    print(f"Recursive search: {'ENABLED' if args.recursive else 'DISABLED'}")
    print(f"Sample ratio: {args.sample_ratio:.1%}")
    print(f"Validation ratio: {args.val_ratio:.1%}")
    print(f"Smart merge: {'ENABLED' if args.enable_smart_merge else 'DISABLED'}")
    print("=" * 70)

    all_files = collect_all_files(args.input_dir, recursive=args.recursive)
    if not all_files:
        print("[ERROR] No *_functions.txt files found in input directory!")
        sys.exit(1)

    top_symbols = None
    pattern = None
    if args.enable_smart_merge:
        if os.path.exists(symbols_file):
            top_symbols, pattern = load_top_symbols(symbols_file)
        else:
            top_symbols, pattern = get_top_symbols(all_files, args.top_n, symbols_file)

    print("\n[STEP] Counting total functions...")
    total_lines = sum(count_lines_in_file(f) for f in tqdm(all_files, desc="Counting"))
    print(f"[INFO] Total functions: {total_lines:,}")

    print("\n[STEP] Sampling and combining files...")
    all_lines = []
    for filepath in tqdm(all_files, desc="Processing"):
        all_lines.extend(
            sample_lines_from_file(
                filepath,
                args.sample_ratio,
                top_symbols=top_symbols,
                pattern=pattern,
            )
        )

    print(f"[INFO] Collected {len(all_lines):,} function lines before shuffle")
    random.shuffle(all_lines)
    print("[INFO] Shuffled all function lines")

    train_lines, val_lines = split_train_val(all_lines, args.val_ratio)
    write_lines(train_lines, train_output)
    if val_lines:
        write_lines(val_lines, val_output)
    else:
        print("[INFO] Validation split disabled or empty; skipped val output")

    print("\n" + "=" * 70)
    print("SUMMARY")
    print("=" * 70)
    print(f"Input files: {len(all_files)}")
    print(f"Input functions: {total_lines:,}")
    print(f"Sampled functions: {len(all_lines):,}")
    print(f"Train functions: {len(train_lines):,}")
    print(f"Val functions: {len(val_lines):,}")
    print(f"Seed: {args.seed}")
    if args.enable_smart_merge:
        print(f"Top symbols file: {symbols_file}")
    print("=" * 70)
    print("[SUCCESS] Function-level pretraining corpora are ready")


if __name__ == "__main__":
    main()
